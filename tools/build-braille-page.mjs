import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = relative => readFile(path.join(root, relative), 'utf8');
const [template, css, brailleFont, monoFont, brailleLicense, monoLicense, bundle] = await Promise.all([
  read('src/braille/converter-page.template.html'),
  read('src/braille/converter-page.css'),
  readFile(path.join(root, 'site/assets/dejavu-braille.woff2')),
  readFile(path.join(root, 'site/assets/jetbrains-mono-latin-500.woff2')),
  read('site/licenses/DejaVu-LICENSE.txt'),
  read('site/licenses/JetBrainsMono-OFL.txt'),
  build({ entryPoints: [path.join(root, 'src/braille/converter-page.js')], bundle: true, write: false, format: 'iife', platform: 'browser', target: ['es2020'], minify: false, legalComments: 'inline' }),
]);

const styles = css.replace('__BRAILLE_FONT__', 'data:font/woff2;base64,' + brailleFont.toString('base64')).replace('__MONO_FONT__', 'data:font/woff2;base64,' + monoFont.toString('base64'));
const script = bundle.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
const license = ('Bundled font licenses\n\n' + brailleLicense + '\n\n' + monoLicense).replace(/--/g, '- -');
const result = template.replace('/*__PAGE_CSS__*/', () => styles).replace('/*__PAGE_JS__*/', () => script).replace('</html>', '<!--\n' + license + '\n-->\n</html>');
const output = path.join(root, 'src/braille/image-to-braille.html');
await writeFile(output, '<!-- Generated by node tools/build-braille-page.mjs. Edit the converter-page source files, then rebuild. -->\n' + result);
console.log('Built src/braille/image-to-braille.html (' + Buffer.byteLength(result) + ' bytes). All fonts, styles and scripts are embedded.');
